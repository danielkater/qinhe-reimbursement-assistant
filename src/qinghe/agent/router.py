"""本地分流器（决策 D1）：判断输入是不是查单请求。

【后续复用：核心模块】后面阶段的问答服务在调用模型之前，都要先经过这里。

查单请求不能发给外部模型，所以这一步完全在本地用规则判断，不调用模型。
宁可多拦：误判只会让用户改到查单入口，漏判才可能让文字外发。
“单据被财务退回怎么办”这类制度问题不算查单，所以不能只看“单据”两个字。
"""
import re

# 报销单号，例如 BX-2026-0101、R-0001
CLAIM_ID = re.compile(r"\b[A-Za-z]{1,4}-\d{2,4}(?:-\d{2,6})?\b")
CLAIM_INTENT = re.compile(
    r"查单"
    r"|(?:查|看|找)[^，。？！]{0,8}(?:单据|报销单|单子|的单)"
    r"|我的[^，。？！]{0,4}(?:单据|报销单|单子|单)"
    r"|(?:单据|报销单|单子|报销|这笔|那笔)[^，。？！]{0,6}(?:到哪|进度|状态|批了|审批到)"
    r"|[一-龥]{1,3}的(?:单据|报销单|单子)"
)


def is_claim_request(text: str) -> bool:
    """带单号或属于查单意图时返回 True。"""
    return bool(CLAIM_ID.search(text) or CLAIM_INTENT.search(text))
